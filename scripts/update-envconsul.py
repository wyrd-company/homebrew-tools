#!/usr/bin/env python3
# relationships:
#   generates: envconsul
#   references: update-envconsul
"""Update the latest envconsul formula from authenticated release checksums."""

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
from urllib.request import Request, urlopen


LATEST_RELEASE = "https://api.github.com/repos/hashicorp/envconsul/releases/latest"
RELEASES = "https://releases.hashicorp.com/envconsul"
PUBLIC_KEY = "https://www.hashicorp.com/.well-known/pgp-key.txt"
# https://developer.hashicorp.com/well-architected-framework/verify-hashicorp-binary
SIGNING_KEY = "C874011F0AB405110D02105534365D9472D7468F"
PLATFORMS = ("darwin_amd64", "darwin_arm64", "linux_amd64", "linux_arm64")
FORMULA = Path(__file__).resolve().parents[1] / "Formula/envconsul.rb"


def download(url, *, github=False):
    headers = {"User-Agent": "homebrew-tools-envconsul"}
    if github:
        headers["Accept"] = "application/vnd.github+json"
        token = os.environ.get("GH_TOKEN")
        if token:
            headers["Authorization"] = f"Bearer {token}"
    with urlopen(Request(url, headers=headers)) as response:
        return response.read()


def verify_signature(directory):
    keyring = directory / "keyring"
    keyring.mkdir(mode=0o700)
    command = [
        "gpg", "--no-options", "--batch", "--no-auto-key-retrieve",
        "--homedir", str(keyring),
    ]
    subprocess.run(
        [*command, "--import", str(directory / "key.asc")],
        check=True, capture_output=True,
    )
    result = subprocess.run(
        [*command, "--status-fd", "1", "--verify",
         str(directory / "SHA256SUMS.sig"), str(directory / "SHA256SUMS")],
        check=True, capture_output=True, text=True,
    )
    good_signers = {
        line.split()[2]
        for line in result.stdout.splitlines()
        if line.startswith("[GNUPG:] GOODSIG ")
    }
    if not good_signers:
        raise ValueError("SHA256SUMS signature is not currently valid")
    if not any(
        line.startswith("[GNUPG:] VALIDSIG ") and line.split()[-1] == SIGNING_KEY
        and any(line.split()[2].endswith(signer) for signer in good_signers)
        for line in result.stdout.splitlines()
    ):
        raise ValueError("SHA256SUMS was not signed by the HashiCorp signing key")


def release_checksums(version):
    base = f"{RELEASES}/{version}/envconsul_{version}"
    with tempfile.TemporaryDirectory(prefix="envconsul-") as temporary:
        directory = Path(temporary)
        for name, url in (
            ("SHA256SUMS", f"{base}_SHA256SUMS"),
            ("SHA256SUMS.sig", f"{base}_SHA256SUMS.sig"),
            ("key.asc", PUBLIC_KEY),
        ):
            (directory / name).write_bytes(download(url))
        verify_signature(directory)
        checksums = {}
        for line in (directory / "SHA256SUMS").read_text().splitlines():
            match = re.fullmatch(r"([0-9a-f]{64})\s+\*?(\S+)", line)
            if not match:
                raise ValueError(f"Invalid SHA256SUMS entry: {line!r}")
            digest, filename = match.groups()
            if filename in checksums:
                raise ValueError(f"Duplicate SHA256SUMS entry: {filename}")
            checksums[filename] = digest
        verified = {}
        for platform in PLATFORMS:
            filename = f"envconsul_{version}_{platform}.zip"
            expected = checksums[filename]
            archive = download(f"{base}_{platform}.zip")
            if hashlib.sha256(archive).hexdigest() != expected:
                raise ValueError(f"SHA256 mismatch: {filename}")
            verified[platform] = expected
        return verified


def render_formula(version, checksums):
    lines = [
        "# This file is generated by scripts/update-envconsul.py. Do not edit.",
        "# relationships:",
        "#   generated-by: update-envconsul",
        "class Envconsul < Formula",
        '  desc "Launch a subprocess with environment variables from Consul and Vault"',
        '  homepage "https://github.com/hashicorp/envconsul"',
        f'  version "{version}"',
        '  license "MPL-2.0"',
    ]
    for os_name, brew_os in (("darwin", "macos"), ("linux", "linux")):
        lines.extend(["", f"  on_{brew_os} do"])
        for index, (arch, brew_arch) in enumerate((("arm64", "arm"), ("amd64", "intel"))):
            if index:
                lines.append("")
            lines.extend([
                f"    on_{brew_arch} do",
                f'      url "{RELEASES}/{version}/envconsul_{version}_{os_name}_{arch}.zip"',
                f'      sha256 "{checksums[f"{os_name}_{arch}"]}"',
                "    end",
            ])
        lines.append("  end")
    lines.extend([
        "", "  def install", '    bin.install "envconsul"', "  end",
        "", "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/envconsul -version")',
        "  end", "end", "",
    ])
    return "\n".join(lines)


def update(formula=FORMULA):
    release = json.loads(download(LATEST_RELEASE, github=True))
    tag = release["tag_name"]
    if release["draft"] or release["prerelease"] or not re.fullmatch(r"v?\d+\.\d+\.\d+", tag):
        raise ValueError(f"Expected a stable release tag, got {tag!r}")
    version = tag.removeprefix("v")
    if formula.exists():
        current = re.search(r'^  version "(\d+\.\d+\.\d+)"$', formula.read_text(), re.MULTILINE)
        if not current:
            raise ValueError("Cannot read the existing envconsul formula version")
        if tuple(map(int, current[1].split("."))) >= tuple(map(int, version.split("."))):
            print(f"envconsul {current[1]} is already up to date")
            return
    checksums = release_checksums(version)
    formula.write_text(render_formula(version, checksums))
    print(f"Updated {formula.name} to envconsul {version}")


if __name__ == "__main__":
    update()
